"""Read-only S2 receipt checks plus dedicated temporary-root I/O.
Usage: python -B docs/reviews/v2_s2_receipt_probe.py --repo-root <repo> [--scratch-root <existing-dir>] [--expect-fixed]
No runtime source is edited. Default verifies the original observations; --expect-fixed requires both fixes.
The tested root is always generated by tempfile under the specified scratch directory.
"""
import argparse
import json
import os
import sys
import tempfile
import unittest

parser = argparse.ArgumentParser()
parser.add_argument("--repo-root", required=True)
parser.add_argument("--scratch-root")
parser.add_argument("--expect-fixed", action="store_true")
args, remaining = parser.parse_known_args()
repo_root = os.path.abspath(args.repo_root)
sys.path.insert(0, repo_root)
sys.path.insert(0, os.path.join(repo_root, "tests", "v2_persistence_local"))
if args.scratch_root:
    scratch = os.path.abspath(args.scratch_root)
    if not os.path.isdir(scratch):
        parser.error("--scratch-root must already exist")
    tempfile.tempdir = scratch

import l_helpers as H
from v2_persistence.local import LocalFileStore, LocalStoreError
from v2_persistence.store import reconcile

class ReceiptProbes(H.RootCase):
    def setUp(self):
        super().setUp()
        self.sc = H.Scenario()
        self.store_ = LocalFileStore(self.root, writable=True, durability="file_sync_only")
        self.store_.initialize(self.sc.genesis)
        self.before = H.raw(self.root)
        d = self.sc.day(1)
        self.sc.observe(d, 47)
        self.plan = self.sc.prepare(self.store_.read(), d).plan

    def diagnostic(self, label, e):
        print(json.dumps({"case": label, "code": e.code, "field": e.field,
                          "phase": e.phase, "cleanup": e.cleanup, "primary": e.primary,
                          "lock_exists": H.LOCK in H.listing(self.root),
                          "tmp_count": len([n for n in H.listing(self.root) if n.endswith(".tmp")]),
                          "old_bytes_unchanged": H.raw(self.root) == self.before}, sort_keys=True))

    def test_r01_prepublication_combined_cleanup(self):
        ops = H.FaultOps().fail("write", "tmp").fail("unlink", "tmp").fail("unlink", "lock")
        with self.assertRaises(LocalStoreError) as cm:
            LocalFileStore(self.root, writable=True, durability="file_sync_only", _ops=ops).commit(self.plan)
        e = cm.exception
        self.diagnostic("r01_tmp_and_lock_cleanup_fail", e)
        self.assertEqual((e.code, e.field, e.phase), ("store_io_error", "lock", "lock_release"))
        self.assertEqual(e.primary, "store_io_error")
        self.assertEqual(set(e.cleanup), {"tmp_left", "lock_left"} if args.expect_fixed else {"lock_left"})
        self.assertIn(H.LOCK, H.listing(self.root))
        self.assertEqual(len([n for n in H.listing(self.root) if n.endswith(".tmp")]), 1)
        self.assertEqual(H.raw(self.root), self.before)
        with self.assertRaises(LocalStoreError) as blocked:
            LocalFileStore(self.root).read()
        self.assertEqual(blocked.exception.code, "store_busy")

    def test_control_foreign_lock_keeps_both_cleanup_items(self):
        def change_lock():
            H.put(self.root, H.LOCK, b"other owner\n")
        ops = H.FaultOps().add("close", "tmp", after=change_lock).fail("unlink", "tmp")
        with self.assertRaises(LocalStoreError) as cm:
            LocalFileStore(self.root, writable=True, durability="file_sync_only", _ops=ops).commit(self.plan)
        e = cm.exception
        self.diagnostic("control_tmp_cleanup_and_foreign_lock", e)
        self.assertEqual(e.code, "store_lock_ownership_lost")
        self.assertEqual(set(e.cleanup), {"tmp_left", "lock_not_ours_left_untouched"})
        self.assertEqual(len([n for n in H.listing(self.root) if n.endswith(".tmp")]), 1)
        self.assertEqual(H.raw(self.root, H.LOCK), b"other owner\n")
        self.assertEqual(H.raw(self.root), self.before)

    def test_control_uncertain_combined_cleanup_keeps_both(self):
        ops = H.FaultOps().fail("replace").fail("unlink", "tmp").fail("unlink", "lock")
        with self.assertRaises(LocalStoreError) as cm:
            LocalFileStore(self.root, writable=True, durability="file_sync_only", _ops=ops).commit(self.plan)
        e = cm.exception
        self.diagnostic("control_replace_attempt_both_retained", e)
        self.assertEqual(e.code, "store_commit_uncertain")
        self.assertEqual(set(e.cleanup), {"tmp_left", "lock_left"})
        self.assertEqual(H.raw(self.root), self.before)

    def test_control_file_sync_only_rerun(self):
        self.store_.commit(self.plan)
        after = H.raw(self.root)
        snap = LocalFileStore(self.root).read()
        self.assertEqual(reconcile(self.plan, snap).status, "ALREADY_APPLIED")
        self.assertEqual(H.raw(self.root), after)
        with self.assertRaises(LocalStoreError) as cm:
            self.store_.commit(self.plan)
        self.assertEqual(cm.exception.code, "cas_conflict")
        self.assertEqual(H.raw(self.root), after)

    def test_r02_existing_lock_directory(self):
        os.mkdir(os.path.join(self.root, H.LOCK))
        with self.assertRaises(LocalStoreError) as cm:
            LocalFileStore(self.root).read()
        e = cm.exception
        self.diagnostic("r02_existing_lock_directory", e)
        expected = "store_busy" if args.expect_fixed or os.name != "nt" else "store_io_error"
        self.assertEqual((e.code, e.field, e.phase), (expected, "lock", "lock_acquire"))
        self.assertTrue(os.path.isdir(os.path.join(self.root, H.LOCK)))
        self.assertEqual(H.raw(self.root), self.before)

if __name__ == "__main__":
    unittest.main(argv=[sys.argv[0]] + remaining, verbosity=2)
